#!/usr/bin/env python3
"""Regenerate ../webpage.h from index.html. Run after editing the page:

    python3 web/embed.py

The page is stored in flash (PROGMEM) as one raw string literal and served by
webserver.cpp, so the board needs no filesystem upload step.
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "index.html")
dst = os.path.join(here, "..", "webpage.h")
DELIM = "PGPAGE"

with open(src, encoding="utf-8") as f:
    html = f.read()

if ")" + DELIM + '"' in html:
    raise SystemExit("index.html contains the raw-string terminator; pick another delimiter")

with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("// webpage.h: GENERATED by web/embed.py from web/index.html. Do not edit by hand.\n")
    f.write("#ifndef PAANIGUARD_WEBPAGE_H\n#define PAANIGUARD_WEBPAGE_H\n\n#include <pgmspace.h>\n\n")
    f.write('static const char WEBPAGE_HTML[] PROGMEM = R"%s(' % DELIM)
    f.write(html)
    f.write(')%s";\n\n#endif // PAANIGUARD_WEBPAGE_H\n' % DELIM)

print("wrote %s (%d bytes of page)" % (os.path.normpath(dst), len(html.encode("utf-8"))))
